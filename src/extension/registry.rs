/// Searches the registered extension index using binary search in O(log N) time.
pub fn find_registered_format(ext: &str) -> Option<&'static str> {
    SORTED_EXTENSION_REGISTRY
        .binary_search_by(|&(registered_ext, _)| registered_ext.cmp(ext))
        .ok()
        .map(|idx| SORTED_EXTENSION_REGISTRY[idx].1)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_registry_is_strictly_sorted_without_duplicates() {
        for window in SORTED_EXTENSION_REGISTRY.windows(2) {
            let (ext1, _) = window[0];
            let (ext2, _) = window[1];
            assert!(
                ext1 < ext2,
                "Registry disorder detected: '{}' is not strictly less than '{}'",
                ext1,
                ext2
            );
        }
    }
}
